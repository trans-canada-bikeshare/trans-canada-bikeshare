// Regenerates public/og-image.html: the 1200x630 social card composition.
//
// Everything the page needs is inlined — the wordmark SVG from public/logo.svg
// and the Inter Tight variable font as a data: URI — so the render is identical
// on any machine and needs no network. See public/og-image-PROVENANCE.md.
//
// Run from anywhere:  node scripts/make-og-image.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Resolved from this file, not from the shell's cwd: a generator that writes
// its output somewhere else depending on where it was invoked is a generator
// that will one day write it nowhere.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const font = fs.readFileSync(
  path.join(root, "node_modules/@fontsource-variable/inter-tight/files/inter-tight-latin-wght-normal.woff2"),
);

// The logo, minus two things that do not belong in a fixed-colour PNG: the XML
// header attributes we re-declare here, and its `prefers-color-scheme: dark`
// rule, which would paint the bicycle #ededed — invisible on paper — whenever
// the rendering browser happened to be in dark mode.
const logo = fs
  .readFileSync(path.join(root, "public/logo.svg"), "utf8")
  .replace(/<!--[\s\S]*?-->/g, "")
  .replace(/<style>[\s\S]*?<\/style>/, "")
  .replace(/ role="img"| aria-label="[^"]*"/g, "")
  .replace(/class="bike"/, 'fill="#090e11" stroke="#090e11"')
  .replace(/\n\s*\n/g, "\n")
  .trim();

const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <title>Trans-Canada Bikeshare — social card source (1200x630)</title>
    <meta name="robots" content="noindex" />
    <!--
      SOURCE FOR public/og-image.png. Not a page of the site.

      Render it at exactly 1200x630 with a headed browser and save the result as
      public/og-image.png; the command and the rights for every asset are in
      public/og-image-PROVENANCE.md. Nothing here is fetched: the typeface is a
      data: URI and the lockup is inline SVG, so the card composes identically
      offline and on any machine.

      No figure from the data appears here on purpose. A number baked into a PNG
      cannot be regenerated by the pipeline that owns it, and this project's
      rule is that copy derives from the data window rather than remembering it.
    -->
    <style>
      @font-face {
        font-family: "Inter Tight";
        font-style: normal;
        font-weight: 100 900;
        font-display: block;
        src: url(data:font/woff2;base64,${font.toString("base64")}) format("woff2");
      }

      /* Light tokens, verbatim from src/index.css. The card is a fixed image;
         it does not follow the viewer's theme, so it commits to paper. */
      :root {
        color-scheme: light;
        --paper: #f7f9fb;
        --ink: #090e11;
        --muted: #636a6f;
        --rule: #d4d8db;
        --van: #196ea9;
        --mtl: #0f766e;
        --tor: #a16207;
      }

      * { margin: 0; padding: 0; box-sizing: border-box; }

      html, body { background: var(--paper); }

      .card {
        width: 1200px;
        height: 630px;
        background: var(--paper);
        color: var(--ink);
        font-family: "Inter Tight", sans-serif;
        font-feature-settings: "rlig" 1, "calt" 1, "tnum" 1;
        -webkit-font-smoothing: antialiased;
        padding: 76px 88px 64px;
        display: flex;
        flex-direction: column;
        justify-content: space-between;
        overflow: hidden;
      }

      .lockup { display: flex; align-items: center; gap: 16px; }
      .lockup svg { width: 132px; height: auto; display: block; }
      .wordmark {
        font-size: 26px;
        font-weight: 500;
        letter-spacing: -0.01em;
      }

      .eyebrow {
        font-size: 17px;
        font-weight: 500;
        text-transform: uppercase;
        letter-spacing: 0.14em;
        color: var(--muted);
      }

      h1 {
        margin-top: 26px;
        max-width: 20ch;
        font-size: 78px;
        font-weight: 500;
        line-height: 0.95;
        letter-spacing: -0.024em;
      }

      .foot {
        display: flex;
        align-items: baseline;
        justify-content: space-between;
        gap: 24px;
        border-top: 1px solid var(--rule);
        padding-top: 22px;
        font-size: 20px;
      }

      .cities { display: flex; gap: 30px; }
      .city { display: flex; align-items: center; gap: 10px; }
      .swatch { width: 12px; height: 12px; flex: none; }
      .url { color: var(--muted); letter-spacing: -0.01em; }
    </style>
  </head>
  <body>
    <div class="card">
      <div class="lockup">
        ${logo.replace(/\n/g, "\n        ")}
        <span class="wordmark">Trans-Canada Bikeshare</span>
      </div>

      <div>
        <p class="eyebrow">Canada · three systems · one method</p>
        <h1>Canada&rsquo;s bike share systems, measured the same way.</h1>
      </div>

      <div class="foot">
        <div class="cities">
          <span class="city"><span class="swatch" style="background: var(--van)"></span>Vancouver</span>
          <span class="city"><span class="swatch" style="background: var(--mtl)"></span>Montreal</span>
          <span class="city"><span class="swatch" style="background: var(--tor)"></span>Toronto</span>
        </div>
        <span class="url">bikeshare.adnanreza.com</span>
      </div>
    </div>
  </body>
</html>
`;

fs.writeFileSync(path.join(root, "public/og-image.html"), html);
console.log("wrote public/og-image.html", html.length, "bytes");
